def name():
    while True:
        suffix = random.choice(SUFFIX)
        if suffix == 'لقطع غيار':
            suffix += ' ' + random.choice(BRANDS)
        words = [random.choice(PREFIX), random.choice(PROPER), suffix]
        n = ' '.join(w for w in words if w)
        if n not in FRESH:
            return n

def phone():
    m = '01' + random.choice('0125') + ''.join(random.choice('0123456789') for _ in range(8))
    f = random.randrange(6)
    s = [m, f'{m[:3]} {m[3:7]} {m[7:]}', f'{m[:4]} {m[4:7]} {m[7:]}', f'+20 {m[1:4]} {m[4:7]} {m[7:]}', f'{m[:4]}-{m[4:7]}-{m[7:]}', m][f]
    if random.random() < 0.35:
        s = ''.join(AR[int(c)] if c.isdigit() else c for c in s)
    return (random.choice(LABEL) + ' ' + s).strip()

def landline():
    code = random.choice(['02', '03', '040', '050', '055', '088', '082'])
    return f'{random.choice(["ت أرضي:", "ت:", "تليفون:"])} {code} {random.randrange(10**6, 10**7)}'

def address():
    num = f'{random.randrange(1, 200)} ' if random.random() < 0.6 else ''
    return f'{num}{random.choice(STREET_WORD)} {random.choice(STREETS)} - {random.choice(PLACES)}'

